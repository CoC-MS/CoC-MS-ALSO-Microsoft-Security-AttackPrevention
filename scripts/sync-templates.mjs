import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { policyGroups } from "../mappings.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const templatesDir = join(root, "templates");

export function endpointPlatform(policy, path) {
  const evidence = `${path} ${policy.displayName ?? policy.name ?? ""} ${policy.platforms ?? ""} ${policy["@odata.type"] ?? ""}`;
  if (/Windows Server/i.test(evidence)) return "Windows Server";
  if (/macOS/i.test(evidence)) return "macOS";
  if (/Android/i.test(evidence)) return "Android";
  if (/iOS|iPadOS/i.test(evidence)) return "iOS / iPadOS";
  if (/Windows/i.test(evidence)) return "Windows";
  if (/Linux/i.test(evidence)) return "Linux";
  throw new Error(`Unknown endpoint platform: ${path}`);
}

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(entries.map((entry) => entry.isDirectory()
    ? walk(join(dir, entry.name)) : [join(dir, entry.name)]));
  return nested.flat();
}

export async function collectTemplates() {
  const files = (await walk(templatesDir)).filter((file) => file.endsWith(".json")
    && !/[\\/]Groups[\\/]/.test(file) && !file.endsWith("MigrationTable.json")).sort();
  const templates = [];
  for (const file of files) {
    const parts = relative(templatesDir, file).split(sep);
    const bytes = await readFile(file);
    const utf16 = bytes[0] === 0xff && bytes[1] === 0xfe;
    const json = JSON.parse(bytes.toString(utf16 ? "utf16le" : "utf8").replace(/^\uFEFF/, ""));
    templates.push({
      folder: parts[0],
      section: parts.at(-2) === parts[0] ? "" : parts.at(-2),
      platformFolder: parts.slice(1, -2).join(" / "),
      platform: ["CompliancePolicies", "SettingsCatalog", "DeviceConfiguration", "Applications"].includes(parts.at(-2)) ? endpointPlatform(json, parts.join("/")) : null,
      path: parts.join("/"),
      name: json.displayName ?? json.name ?? parts.at(-1).replace(/\.json$/, ""),
      description: (json.description ?? "").trim(),
      state: json.state ?? null,
      controls: parts.at(-2) === "ConditionalAccess" ? policyGroups(json) : [],
      type: json["@odata.type"] ?? null
    });
  }
  return templates;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const templates = await collectTemplates();
  await writeFile(join(root, "data", "templates.js"),
    `// Generated by scripts/sync-templates.mjs from the templates/ folder. Do not edit by hand.\nexport default ${JSON.stringify({ templates }, null, 2)};\n`);
  console.log(`Wrote ${templates.length} templates`);
}
